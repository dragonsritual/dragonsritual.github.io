-- Secure member-side helpers for page access checks.
create or replace function public.dr_my_page_permissions()
returns text[]
language sql
stable
security definer
set search_path=public
as $$
  select coalesce(array_agg(path order by path),'{}'::text[])
  from public.dr_member_page_permissions
  where user_id=auth.uid();
$$;

revoke all on function public.dr_my_page_permissions() from public;
grant execute on function public.dr_my_page_permissions() to authenticated;

-- Account-status helper.
create or replace function public.dr_my_account_status()
returns text
language sql
stable
security definer
set search_path=public
as $$
  select coalesce(
    (select account_status from public.dr_member_profiles where user_id=auth.uid()),
    'active'
  );
$$;

revoke all on function public.dr_my_account_status() from public;
grant execute on function public.dr_my_account_status() to authenticated;
