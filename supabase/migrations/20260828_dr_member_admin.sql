create or replace function public.dr_admin_set_member_status(
  target_user uuid,
  new_status text
)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.is_admin() then
    raise exception 'admin required';
  end if;

  if new_status not in ('active','paused','suspended','removed') then
    raise exception 'invalid status';
  end if;

  update public.dr_member_profiles
  set account_status=new_status,
      updated_at=now()
  where user_id=target_user;

  if new_status in ('suspended','removed') then
    delete from public.dr_member_roles
    where user_id=target_user
      and role <> 'member';
  end if;

  insert into public.dr_member_admin_audit(actor_user_id,target_user_id,action,metadata)
  values(auth.uid(),target_user,'status_changed',jsonb_build_object('status',new_status));
end;
$$;

create or replace function public.dr_admin_replace_member_roles(
  target_user uuid,
  new_roles text[]
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  r text;
begin
  if not public.is_admin() then
    raise exception 'admin required';
  end if;

  -- Never allow this RPC to create admin/director privilege.
  if exists(
    select 1 from unnest(coalesce(new_roles,'{}'::text[])) x
    where x in ('admin','director','founder')
  ) then
    raise exception 'admin/director roles cannot be assigned here';
  end if;

  delete from public.dr_member_roles
  where user_id=target_user and role<>'member';

  insert into public.dr_member_roles(user_id,role,assigned_by)
  values(target_user,'member',auth.uid())
  on conflict do nothing;

  foreach r in array coalesce(new_roles,'{}'::text[]) loop
    if r in ('creator','writer','illustrator','radio','comics','streaming','3d','editor') then
      insert into public.dr_member_roles(user_id,role,assigned_by)
      values(target_user,r,auth.uid())
      on conflict do nothing;
    end if;
  end loop;

  -- Assigning any creator/workstation role automatically ensures creator.
  if exists(
    select 1 from unnest(coalesce(new_roles,'{}'::text[])) x
    where x in ('writer','illustrator','radio','comics','streaming','3d','editor')
  ) then
    insert into public.dr_member_roles(user_id,role,assigned_by)
    values(target_user,'creator',auth.uid())
    on conflict do nothing;
  end if;

  update public.dr_member_profiles
  set account_status='active',updated_at=now()
  where user_id=target_user;

  insert into public.dr_member_admin_audit(actor_user_id,target_user_id,action,metadata)
  values(auth.uid(),target_user,'roles_replaced',jsonb_build_object('roles',new_roles));
end;
$$;

create or replace function public.dr_admin_replace_member_badges(
  target_user uuid,
  new_badges text[]
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  b text;
begin
  if not public.is_admin() then
    raise exception 'admin required';
  end if;

  delete from public.dr_member_badges_admin where user_id=target_user;

  foreach b in array coalesce(new_badges,'{}'::text[]) loop
    if exists(select 1 from public.dr_badge_definitions where id=b and active=true) then
      insert into public.dr_member_badges_admin(user_id,badge_id,awarded_by)
      values(target_user,b,auth.uid())
      on conflict do nothing;
    end if;
  end loop;

  insert into public.dr_member_admin_audit(actor_user_id,target_user_id,action,metadata)
  values(auth.uid(),target_user,'badges_replaced',jsonb_build_object('badges',new_badges));
end;
$$;

create or replace function public.dr_admin_replace_member_page_permissions(
  target_user uuid,
  new_paths text[]
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  p text;
begin
  if not public.is_admin() then
    raise exception 'admin required';
  end if;

  delete from public.dr_member_page_permissions where user_id=target_user;

  foreach p in array coalesce(new_paths,'{}'::text[]) loop
    if left(p,1)='/' and length(p)<=240 then
      insert into public.dr_member_page_permissions(user_id,path,granted_by)
      values(target_user,p,auth.uid())
      on conflict do nothing;
    end if;
  end loop;

  insert into public.dr_member_admin_audit(actor_user_id,target_user_id,action,metadata)
  values(auth.uid(),target_user,'page_permissions_replaced',jsonb_build_object('paths',new_paths));
end;
$$;

create or replace function public.dr_admin_set_member_note(
  target_user uuid,
  new_note text
)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.is_admin() then
    raise exception 'admin required';
  end if;

  update public.dr_member_profiles
  set director_note=left(coalesce(new_note,''),5000),
      updated_at=now()
  where user_id=target_user;

  insert into public.dr_member_admin_audit(actor_user_id,target_user_id,action)
  values(auth.uid(),target_user,'director_note_updated');
end;
$$;

