  add column if not exists account_status text not null default 'active',
  add column if not exists director_note text,
  add column if not exists last_active_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname='dr_member_profiles_account_status_check'
  ) then
    alter table public.dr_member_profiles
      add constraint dr_member_profiles_account_status_check
      check (account_status in ('active','paused','suspended','removed'));
  end if;
end $$;

-- Badge catalog for admin assignment.
create table if not exists public.dr_badge_definitions (
  id text primary key,
  name text not null,
  description text not null default '',
  category text not null default 'community',
  active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.dr_member_badges_admin (
  user_id uuid not null references auth.users(id) on delete cascade,
  badge_id text not null references public.dr_badge_definitions(id) on delete cascade,
  awarded_by uuid references auth.users(id) on delete set null,
  awarded_at timestamptz not null default now(),
  primary key(user_id,badge_id)
);

-- Per-member explicit route allowance.
create table if not exists public.dr_member_page_permissions (
  user_id uuid not null references auth.users(id) on delete cascade,
  path text not null,
  granted_by uuid references auth.users(id) on delete set null,
  granted_at timestamptz not null default now(),
  primary key(user_id,path)
);

-- Immutable-ish admin audit.
create table if not exists public.dr_member_admin_audit (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.dr_badge_definitions enable row level security;
alter table public.dr_member_badges_admin enable row level security;
alter table public.dr_member_page_permissions enable row level security;
alter table public.dr_member_admin_audit enable row level security;

